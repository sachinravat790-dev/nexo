// 🔍 Helper: Expand user query with synonyms
function expandQueryWords(searchQuery) {
  const clean = searchQuery.trim().toLowerCase();
  const words = clean.split(/\s+/).filter(Boolean);
  const expanded = new Set(words);
  expanded.add(clean);

  words.forEach((w) => {
    // Direct synonym lookup
    if (SYNONYM_MAP[w]) {
      SYNONYM_MAP[w].forEach((syn) => expanded.add(syn));
    }
    // Partial synonym match (e.g. "shoes" -> matches "shoe")
    Object.keys(SYNONYM_MAP).forEach((k) => {
      if (w.includes(k) || k.includes(w)) {
        SYNONYM_MAP[k].forEach((syn) => expanded.add(syn));
      }
    });
  });

  return Array.from(expanded);
}

// @desc    Get all products with Flipkart-Style Accurate Search & Prices
// @route   GET /api/products
exports.getProducts = async (req, res) => {
  try {
    const { search, category, sort } = req.query;

    // Start with complete Master Catalog (always dependable)
    let results = [...MASTER_PRODUCTS];

    // Merge with any custom products in MongoDB if available
    try {
      const dbProducts = await Product.find({}).limit(50);
      if (dbProducts && dbProducts.length > 0) {
        const masterIds = new Set(results.map((m) => m._id));
        dbProducts.forEach((p) => {
          const id = p._id.toString();
          if (!masterIds.has(id)) {
            results.push({
              _id: id,
              title: p.title,
              description: p.description,
              brand: p.brand || '',
              tags: p.tags || [],
              categoryName: p.category?.name || 'General',
              categorySlug: p.category?.slug || 'general',
              originalPrice: p.originalPrice,
              price: p.price,
              studentPrice: p.studentPrice,
              image: p.image || p.images?.[0] || 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=800&q=80',
              stock: p.stock || 10,
              rating: p.rating || 4.5,
              numReviews: p.numReviews || 100,
              isStudentDeal: p.isStudentDeal !== false,
            });
          }
        });
      }
    } catch (e) {
      // DB offline - Master Catalog handles everything smoothly
    }

    // 1. Filter by Category if selected
    if (category && category !== 'All') {
      const catLower = category.toLowerCase();
      results = results.filter((p) => {
        const pCat = (p.categoryName || '').toLowerCase();
        const pSlug = (p.categorySlug || '').toLowerCase();
        return pCat.includes(catLower) || pSlug.includes(catLower) || catLower.includes(pCat);
      });
    }

    // 2. Flipkart Smart Search Filter (Exact match + Synonyms + Tags + Brand)
    if (search && search.trim()) {
      const searchTerms = expandQueryWords(search);

      results = results.filter((item) => {
        const title = (item.title || '').toLowerCase();
        const desc = (item.description || '').toLowerCase();
        const brand = (item.brand || '').toLowerCase();
        const cat = (item.categoryName || '').toLowerCase();
        const tags = Array.isArray(item.tags) ? item.tags.join(' ').toLowerCase() : '';
        const haystack = `${title} ${desc} ${brand} ${cat} ${tags}`;

        // Return true if ANY expanded synonym or search term matches this product
        return searchTerms.some((term) => haystack.includes(term));
      });
    }

    // 3. Sorting
    if (sort === 'price-low') {
      results.sort((a, b) => a.price - b.price);
    } else if (sort === 'price-high') {
      results.sort((a, b) => b.price - a.price);
    } else if (sort === 'rating') {
      results.sort((a, b) => b.rating - a.rating);
    }

    res.status(200).json({
      success: true,
      count: results.length,
      totalProducts: results.length,
      products: results,
    });
  } catch (error) {
    console.error('getProducts error:', error);
    res.status(200).json({
      success: true,
      count: MASTER_PRODUCTS.length,
      totalProducts: MASTER_PRODUCTS.length,
      products: MASTER_PRODUCTS,
    });
  }
};

// @desc    Get single product by ID
// @route   GET /api/products/:id
exports.getProductById = async (req, res) => {
  try {
    const { id } = req.params;

    // Check in Master Products first
    const masterFound = MASTER_PRODUCTS.find((p) => p._id === id);
    if (masterFound) {
      return res.status(200).json({ success: true, product: masterFound });
    }

    // Try DB
    try {
      const p = await Product.findById(id);
      if (p) {
        return res.status(200).json({ success: true, product: p });
      }
    } catch (e) {}

    return res.status(404).json({ success: false, message: 'Product not found' });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Create new product (Admin)
// @route   POST /api/products
exports.createProduct = async (req, res) => {
  try {
    const newProd = {
      _id: `prod_${Date.now()}`,
      ...req.body,
      createdAt: new Date(),
    };
    MASTER_PRODUCTS.unshift(newProd);

    try {
      await Product.create(req.body);
    } catch (e) {}

    res.status(201).json({ success: true, product: newProd });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};